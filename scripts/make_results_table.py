import argparse
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SUMMARY = ROOT / "results" / "summary.csv"
README = ROOT / "README.md"
START, END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"

ROWS = [
    ("e0_no_retrieval", "E0 no retrieval"),
    ("cs500_ov50_k4_dense", "E1 dense, chunk 500/50, k=4"),
    ("cs1000_ov100_k2_dense", "E3 dense, chunk 1000/100, k=2"),
    ("cs1000_ov100_k4_dense", "**Baseline** dense, chunk 1000/100, k=4"),
    ("cs1000_ov100_k8_dense", "E3 dense, chunk 1000/100, k=8"),
    ("cs1500_ov150_k4_dense", "E2b dense, chunk 1500/150, k=4"),
    ("cs1000_ov100_k4_hybrid", "E4 hybrid BM25+RRF, k=4"),
    ("cs1000_ov100_k4_dense_rerank", "E5 dense + rerank, k=4"),
    ("cs1000_ov100_k4_hybrid_rerank", "**Default** E6 hybrid + rerank, k=4"),
]
COLUMNS = [
    ("hit", "Hit@k"),
    ("recall", "Recall@k"),
    ("mrr", "MRR"),
    ("correct_mean", "Correctness (0-2)"),
    ("correct_full", "Fully correct"),
    ("faith_mean", "Faithfulness (0-2)"),
    ("over_refusal", "Over-refusal"),
    ("correct_abstention", "Correct abstention"),
]
NOT_APPLICABLE_E0 = {"correct_abstention", "over_refusal"}


def cell(row: dict, key: str) -> str:
    if row["name"] == "e0_no_retrieval" and key in NOT_APPLICABLE_E0:
        return "n/a"
    value = row.get(key, "")
    return value if value != "" else "n/a"


def build_table(rows_by_name: dict[str, dict]) -> str:
    header = "| Experiment | " + " | ".join(label for _, label in COLUMNS) + " |"
    divider = "|---|" + "---|" * len(COLUMNS)
    lines = [header, divider]
    for name, label in ROWS:
        if name in rows_by_name:
            row = rows_by_name[name]
            cells = " | ".join(cell(row, key) for key, _ in COLUMNS)
            lines.append(f"| {label} | {cells} |")
    first = next(iter(rows_by_name.values()))
    lines.append("")
    lines.append(
        f"{first['n_answerable']} answerable + {first['n_unanswerable']} unanswerable questions "
        "(`eval/qa.jsonl`). Generated by `scripts/make_results_table.py` "
        "from `results/summary.csv`."
    )
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description="Build the README results table")
    parser.add_argument("--print", action="store_true", dest="print_only")
    args = parser.parse_args()
    with open(SUMMARY, encoding="utf-8", newline="") as f:
        rows_by_name = {row["name"]: row for row in csv.DictReader(f)}
    table = build_table(rows_by_name)
    if args.print_only:
        print(table)
        return
    text = README.read_text(encoding="utf-8")
    assert START in text and END in text, "README.md is missing the RESULTS markers"
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    README.write_text(f"{head}{START}\n{table}\n{END}{tail}", encoding="utf-8")
    print(f"README.md results table updated ({len(rows_by_name)} rows in summary.csv)")


if __name__ == "__main__":
    main()
